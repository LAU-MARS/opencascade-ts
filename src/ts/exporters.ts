/**
 * Pure-TypeScript exporters for the outputs agents actually need: files.
 * Everything here runs headless in Node with no wasm required.
 */

import { computeVertexNormals } from "./mesh-utils.js";
import type { HiddenLineResult, MeshData, Vec3 } from "./types.js";

/** ASCII STL from a tessellated mesh. */
export function meshToAsciiStl(mesh: MeshData, name = "shape"): string {
  const { positions, indices } = mesh;
  const out: string[] = [`solid ${name}`];

  for (let i = 0; i + 2 < indices.length; i += 3) {
    const ia = indices[i]! * 3;
    const ib = indices[i + 1]! * 3;
    const ic = indices[i + 2]! * 3;

    const ax = positions[ia]!, ay = positions[ia + 1]!, az = positions[ia + 2]!;
    const bx = positions[ib]!, by = positions[ib + 1]!, bz = positions[ib + 2]!;
    const cx = positions[ic]!, cy = positions[ic + 1]!, cz = positions[ic + 2]!;

    let nx = (by - ay) * (cz - az) - (bz - az) * (cy - ay);
    let ny = (bz - az) * (cx - ax) - (bx - ax) * (cz - az);
    let nz = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax);
    const len = Math.hypot(nx, ny, nz);
    if (len > 1e-12) {
      nx /= len;
      ny /= len;
      nz /= len;
    } else {
      nx = ny = 0;
      nz = 1;
    }

    out.push(`  facet normal ${nx} ${ny} ${nz}`);
    out.push("    outer loop");
    out.push(`      vertex ${ax} ${ay} ${az}`);
    out.push(`      vertex ${bx} ${by} ${bz}`);
    out.push(`      vertex ${cx} ${cy} ${cz}`);
    out.push("    endloop");
    out.push("  endfacet");
  }
  out.push(`endsolid ${name}`);
  out.push("");
  return out.join("\n");
}

/** Wavefront OBJ (v/f for the surface, l for wireframe segments). */
export function meshToObj(mesh: MeshData): string {
  const { positions, indices, edges } = mesh;
  const out: string[] = ["# generated by opencascade-ts", "o shape"];

  for (let i = 0; i < positions.length; i += 3) {
    out.push(`v ${positions[i]} ${positions[i + 1]} ${positions[i + 2]}`);
  }
  const vertexCount = positions.length / 3;

  for (let i = 0; i < edges.length; i += 3) {
    out.push(`v ${edges[i]} ${edges[i + 1]} ${edges[i + 2]}`);
  }

  for (let i = 0; i + 2 < indices.length; i += 3) {
    out.push(`f ${indices[i]! + 1} ${indices[i + 1]! + 1} ${indices[i + 2]! + 1}`);
  }

  for (let i = 0; i + 5 < edges.length; i += 6) {
    const a = vertexCount + i / 3 + 1;
    const b = vertexCount + i / 3 + 2;
    out.push(`l ${a} ${b}`);
  }
  out.push("");
  return out.join("\n");
}

export interface SvgExportOptions {
  /** Output width in px. Default: fit to `height` or 1:1 model units. */
  width?: number;
  /** Output height in px. Default: fit to `width` or 1:1 model units. */
  height?: number;
  /** Margin in px on every side. Default `10`. */
  margin?: number;
  /** Include hidden edges (dashed). Default `false`. */
  showHidden?: boolean;
  /** `[dash, gap]` in px for hidden edges. Default `[6, 4]`. */
  hiddenDash?: [number, number];
  /** Stroke width in px for visible edges. Default `1.5`. */
  strokeWidth?: number;
}

/**
 * SVG line drawing from a hidden-line-removal result — the classic
 * "technical drawing" output. Projects points onto the frame's x/y axes and
 * flips Y so the drawing reads with +Y up.
 */
export function hiddenLinesToSvg(result: HiddenLineResult, options: SvgExportOptions = {}): string {
  const { xAxis, yAxis } = result;
  const margin = options.margin ?? 10;
  const strokeWidth = options.strokeWidth ?? 1.5;
  const showHidden = options.showHidden ?? false;

  const project = (points: Float32Array): { x: number; y: number }[] => {
    const projected: { x: number; y: number }[] = [];
    for (let i = 0; i + 2 < points.length; i += 3) {
      projected.push({
        x: points[i]! * xAxis[0] + points[i + 1]! * xAxis[1] + points[i + 2]! * xAxis[2],
        y: points[i]! * yAxis[0] + points[i + 1]! * yAxis[1] + points[i + 2]! * yAxis[2],
      });
    }
    return projected;
  };

  const visible = project(result.visible);
  const hidden = showHidden ? project(result.hidden) : [];

  if (visible.length === 0 && hidden.length === 0) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><!-- no edges -->\n</svg>\n`;
  }

  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  const track = (p: { x: number; y: number }): void => {
    minX = Math.min(minX, p.x);
    minY = Math.min(minY, p.y);
    maxX = Math.max(maxX, p.x);
    maxY = Math.max(maxY, p.y);
  };
  visible.forEach(track);
  hidden.forEach(track);

  const dx = Math.max(maxX - minX, 1e-6);
  const dy = Math.max(maxY - minY, 1e-6);

  let width = options.width;
  let height = options.height;
  if (width == null && height == null) {
    width = Math.ceil(dx + 2 * margin);
    height = Math.ceil(dy + 2 * margin);
  }
  const scale =
    width != null && height != null
      ? Math.min((width - 2 * margin) / dx, (height - 2 * margin) / dy)
      : width != null
        ? (width - 2 * margin) / dx
        : (height! - 2 * margin) / dy;

  // SVG's Y axis points down: flip the drawing.
  const toSvgX = (x: number): number => margin + (x - minX) * scale;
  const toSvgY = (y: number): number => margin + (maxY - y) * scale;

  const toPath = (points: { x: number; y: number }[]): string => {
    let d = "";
    for (let i = 0; i + 1 < points.length; i += 2) {
      d += `M${toSvgX(points[i]!.x).toFixed(2)} ${toSvgY(points[i]!.y).toFixed(2)}`;
      d += `L${toSvgX(points[i + 1]!.x).toFixed(2)} ${toSvgY(points[i + 1]!.y).toFixed(2)}`;
    }
    return d;
  };

  const outWidth = width ?? Math.ceil(dx * scale + 2 * margin);
  const outHeight = height ?? Math.ceil(dy * scale + 2 * margin);
  const [dash, gap] = options.hiddenDash ?? [6, 4];

  const parts = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${outWidth}" height="${outHeight}" viewBox="0 0 ${outWidth} ${outHeight}">`,
    `<g fill="none" stroke-linecap="round">`,
    `<path d="${toPath(visible)}" stroke="#111" stroke-width="${strokeWidth}"/>`,
  ];
  if (hidden.length > 0) {
    parts.push(
      `<path d="${toPath(hidden)}" stroke="#888" stroke-width="${Math.max(strokeWidth * 0.6, 0.5)}" stroke-dasharray="${dash} ${gap}"/>`,
    );
  }
  parts.push(`</g>`, `</svg>`, ``);
  return parts.join("\n");
}

/** SVG for plain 3D line segments (e.g. wireframe `mesh.edges`) viewed along a direction. */
export function lineSegmentsToSvg(
  segments: Float32Array,
  direction: Vec3,
  options: SvgExportOptions = {},
): string {
  const up: Vec3 = Math.abs(direction[2]) < 0.9 ? [0, 0, 1] : [0, 1, 0];
  const xAxis = normalize(cross3(up, direction));
  const yAxis = normalize(cross3(direction, xAxis));
  return hiddenLinesToSvg({ visible: segments, hidden: new Float32Array(0), xAxis, yAxis }, options);
}

// --- binary glTF (.glb) ---------------------------------------------------------

export interface GlbExportOptions {
  name?: string;
  /** Include the wireframe as LINE primitives. Default `true`. */
  wireframe?: boolean;
}

/**
 * Binary glTF 2.0 (.glb) from a tessellated mesh — single file, no external
 * buffers. Pure TypeScript: needs no wasm, no OCCT RapidJSON support.
 */
export function meshToGlb(mesh: MeshData, options: GlbExportOptions = {}): Uint8Array {
  const includeWireframe = options.wireframe ?? true;
  const encoder = new TextEncoder();

  // --- binary section: positions, normals, indices, line indices ---
  const normals = computeVertexNormals(mesh.positions, mesh.indices);
  const chunks: ArrayBuffer[] = [];
  const views: Array<{ buffer: number; byteOffset: number; byteLength: number; target?: number }> = [];
  const accessors: Record<string, unknown>[] = [];

  let offset = 0;
  const pushView = (data: ArrayBuffer, target: number | undefined): number => {
    views.push({ buffer: 0, byteOffset: offset, byteLength: data.byteLength, target });
    chunks.push(data);
    offset += data.byteLength;
    // pad to 4 bytes for the next view
    const padding = (4 - (offset % 4)) % 4;
    if (padding > 0) {
      chunks.push(new ArrayBuffer(padding));
      offset += padding;
    }
    return views.length - 1;
  };

  if (mesh.positions.length === 0 || mesh.indices.length === 0) {
    throw new Error("meshToGlb: mesh has no triangles");
  }

  // POSITION
  const positionsView = pushView(mesh.positions.slice().buffer, 34962);
  let min = [Infinity, Infinity, Infinity];
  let max = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < mesh.positions.length; i += 3) {
    for (let axis = 0; axis < 3; axis++) {
      const value = mesh.positions[i + axis]!;
      min[axis] = Math.min(min[axis]!, value);
      max[axis] = Math.max(max[axis]!, value);
    }
  }
  accessors.push({
    bufferView: positionsView,
    componentType: 5126,
    count: mesh.positions.length / 3,
    type: "VEC3",
    min,
    max,
  });

  // NORMAL
  const normalsView = pushView(normals.slice().buffer, 34962);
  accessors.push({
    bufferView: normalsView,
    componentType: 5126,
    count: normals.length / 3,
    type: "VEC3",
  });

  // indices (triangle indices, then optional wireframe line indices as uint32)
  const indicesView = pushView(mesh.indices.slice().buffer, 34963);
  accessors.push({
    bufferView: indicesView,
    componentType: 5125,
    count: mesh.indices.length,
    type: "SCALAR",
  });

  const primitives: Record<string, unknown>[] = [
    { attributes: { POSITION: 0, NORMAL: 1 }, indices: 2, mode: 4 },
  ];

  if (includeWireframe && mesh.edges.length >= 6) {
    // wireframe as lines over the edge vertices: reuse edge points as
    // additional positions is simplest, but they are already in the same
    // buffer — emit them as their own accessor for clarity.
    const positionCount = mesh.positions.length / 3;
    const lineIndices = new Uint32Array(mesh.edges.length / 3);
    for (let i = 0; i < lineIndices.length; i++) {
      lineIndices[i] = positionCount + i;
    }
    const edgesView = pushView(mesh.edges.slice().buffer, 34962);
    accessors.push({
      bufferView: edgesView,
      componentType: 5126,
      count: mesh.edges.length / 3,
      type: "VEC3",
    });
    const lineIndicesView = pushView(lineIndices.buffer, 34963);
    accessors.push({
      bufferView: lineIndicesView,
      componentType: 5125,
      count: lineIndices.length,
      type: "SCALAR",
    });
    primitives.push({
      attributes: { POSITION: 3 },
      indices: 4,
      mode: 1, // LINES
    });
  }

  const binaryLength = offset;
  const gltf = {
    asset: { version: "2.0", generator: "opencascade-ts" },
    scene: 0,
    scenes: [{ nodes: [0], name: options.name ?? "shape" }],
    nodes: [{ mesh: 0, name: options.name ?? "shape" }],
    meshes: [{ primitives }],
    accessors,
    bufferViews: views,
    buffers: [{ byteLength: binaryLength }],
  };

  // --- .glb container: header + JSON chunk (space-padded) + BIN chunk (zero-padded) ---
  const jsonBytes = encoder.encode(JSON.stringify(gltf));
  const jsonPadding = (4 - (jsonBytes.length % 4)) % 4;
  const jsonLength = jsonBytes.length + jsonPadding;

  const binary = new Uint8Array(binaryLength);
  let cursor = 0;
  for (const chunk of chunks) {
    binary.set(new Uint8Array(chunk), cursor);
    cursor += chunk.byteLength;
  }

  const totalLength = 12 + 8 + jsonLength + (binaryLength > 0 ? 8 + binaryLength : 0);
  const glb = new Uint8Array(totalLength);
  const dataView = new DataView(glb.buffer);

  dataView.setUint32(0, 0x46546c67, true); // "glTF"
  dataView.setUint32(4, 2, true); // version
  dataView.setUint32(8, totalLength, true);

  dataView.setUint32(12, jsonLength, true);
  dataView.setUint32(16, 0x4e4f534a, true); // "JSON"
  glb.set(jsonBytes, 20);
  for (let i = 0; i < jsonPadding; i++) {
    glb[20 + jsonBytes.length + i] = 0x20; // spaces
  }

  if (binaryLength > 0) {
    const binHeader = 20 + jsonLength;
    dataView.setUint32(binHeader, binaryLength, true);
    dataView.setUint32(binHeader + 4, 0x004e4942, true); // "BIN\0"
    glb.set(binary, binHeader + 8);
  }

  return glb;
}

function cross3(a: Vec3, b: Vec3): Vec3 {
  return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
}

function normalize(v: Vec3): Vec3 {
  const len = Math.hypot(v[0], v[1], v[2]) || 1;
  return [v[0] / len, v[1] / len, v[2] / len];
}
